"""Manual, authenticated proof; never collected or invoked by pytest.

Run after offline checks. Real bytes are saved only under Git-ignored local paths.
Optional --expected JSON must be independently checked, never generated by this script.
"""

import argparse
import asyncio
import hashlib
import json
import os
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

from dotenv import dotenv_values

from stock_research_ai.adapters.raw_artifacts import FileRawArtifactStore
from stock_research_ai.bootstrap import ingest_market, initialize_database, market_engine
from stock_research_ai.config import Settings
from stock_research_ai.domain.market import MarketRequest


async def run(output: Path, expected: Path | None) -> None:
    credentials = {**dotenv_values(".env"), **os.environ}
    if not credentials.get("KITE_API_KEY") or not credentials.get("KITE_ACCESS_TOKEN"):
        raise ValueError(
            "Configure KITE_API_KEY and KITE_ACCESS_TOKEN locally; do not paste secrets"
        )
    if output.exists():
        raise ValueError("Choose a new output directory")
    settings = Settings(database_path=output / "proof.sqlite3", artifact_path=output / "artifacts")
    await initialize_database(settings)
    truth = json.loads(expected.read_text()) if expected else None
    for symbol, kind in (
        ("YESBANK", "EQUITY"),
        ("INFY", "EQUITY"),
        ("NIFTY 50", "INDEX"),
        ("NIFTY BANK", "INDEX"),
    ):
        request = MarketRequest.model_validate(
            {
                "symbol": symbol,
                "exchange": "NSE",
                "kind": kind,
                "start": "2025-01-02",
                "end": "2025-01-03",
                "expected_sessions": ["2025-01-02", "2025-01-03"],
            }
        )
        result = await ingest_market(settings, request, output / symbol.lower().replace(" ", "-"))
        if result.coverage.overall != "COMPLETE" or result.instrument is None:
            codes = sorted({issue.code for issue in result.coverage.issues})
            raise ValueError(f"{symbol}: {result.coverage.overall}; issues={codes}")
        assert [o.trading_date for o in result.observations] == [date(2025, 1, 2), date(2025, 1, 3)]
        store = FileRawArtifactStore(settings.artifact_path)
        for artifact in result.raw_artifacts:
            raw = await store.read(artifact)
            assert hashlib.sha256(raw).hexdigest() == artifact.content_sha256
        async with market_engine(settings) as engine:
            assert await engine.get_market(result.id) == result
        if truth:
            checks = truth[symbol]
            assert len(checks) == len(result.observations)
            for observation, check in zip(result.observations, checks, strict=True):
                assert observation.trading_date.isoformat() == check["date"]
                for field in ("open", "high", "low", "close", "volume"):
                    assert getattr(observation, field) == Decimal(check[field])
        print(
            f"{symbol}: token={result.instrument.provider_identifier}; 2 daily observations; "
            f"SHA and persistence verified; numerical golden={'PASS' if truth else 'PENDING'}"
        )
    print("Corporate actions: UNAVAILABLE; adjustment basis: UNKNOWN; sessions: caller-declared")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("output/market-live-proof"))
    parser.add_argument(
        "--expected", type=Path, help="Independent real numerical expectations JSON"
    )
    args = parser.parse_args()
    # Prevent accidentally placing real provider responses in tracked fixture directories.
    root = Path(__file__).resolve().parents[1]
    output_path = args.output.resolve()
    if not output_path.is_relative_to(root / "output"):
        parser.error("Live output must be under the repository's Git-ignored output/ directory")
    try:
        asyncio.run(run(output_path, args.expected))
    except (ValueError, AssertionError) as error:
        print(f"Proof incomplete: {error}", file=sys.stderr)
        raise SystemExit(1) from None
